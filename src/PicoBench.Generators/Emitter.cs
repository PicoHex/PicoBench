namespace PicoBench.Generators;

/// <summary>
/// Generates the partial class source code implementing <c>IBenchmarkClass.RunBenchmarksAsync</c>.
/// All types in emitted code use <c>global::</c> qualification to avoid namespace conflicts.
/// </summary>
internal static class Emitter
{
    private const string Bench = "global::PicoBench";
    private const string SystemAction = "global::System.Action";
    private const string ValueTaskType = "global::System.Threading.Tasks.ValueTask";

    public static string Generate(BenchmarkClassModel model)
    {
        var sb = new StringBuilder();
        var isAsync = model.IsAsync;
        var hasParams = model.ParamsProperties.Length > 0;
        var hasIterSetup = model.IterationSetupMethod is not null;
        var hasIterCleanup = model.IterationCleanupMethod is not null;

        // ── File header ──────────────────────────────────────────────
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by PicoBench.Generators — do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        // ── Namespace ────────────────────────────────────────────────
        var indent = "";
        if (model.Namespace is not null)
        {
            sb.AppendLine($"namespace {IdentifierEscaping.EscapeQualifiedName(model.Namespace)}");
            sb.AppendLine("{");
            indent = "    ";
        }

        // ── Partial class + interface ────────────────────────────────
        sb.AppendLine(
            $"{indent}{model.AccessModifier} partial class {Id(model.ClassName)} : {Bench}.IBenchmarkClass"
        );
        sb.AppendLine($"{indent}{{");

        var m1 = indent + "    "; // method indent
        var m2 = m1 + "    "; // body indent

        // ── RunBenchmarksAsync method ─────────────────────────────────
        var asyncKeyword = isAsync ? "async " : "";
        sb.AppendLine($"{m1}/// <inheritdoc/>");
        sb.AppendLine(
            $"{m1}public {asyncKeyword}{ValueTaskType}<{Bench}.BenchmarkSuite> RunBenchmarksAsync({Bench}.BenchmarkConfig? config = null)"
        );
        sb.AppendLine($"{m1}{{");

        sb.AppendLine($"{m2}config ??= {Bench}.BenchmarkConfig.Default;");
        sb.AppendLine(
            $"{m2}var __results = new global::System.Collections.Generic.List<{Bench}.BenchmarkResult>();"
        );
        sb.AppendLine(
            $"{m2}var __comparisons = new global::System.Collections.Generic.List<{Bench}.ComparisonResult>();"
        );
        sb.AppendLine($"{m2}var __sw = global::System.Diagnostics.Stopwatch.StartNew();");
        sb.AppendLine();

        // ── [Params] loops ───────────────────────────────────────────
        var bodyIndent = m2;
        if (hasParams)
        {
            foreach (var p in model.ParamsProperties)
            {
                var valuesLiteral = string.Join(", ", p.FormattedValues);
                sb.AppendLine(
                    $"{bodyIndent}foreach (var __p_{p.Name} in new {p.TypeFullName}[] {{ {valuesLiteral} }})"
                );
                sb.AppendLine($"{bodyIndent}{{");
                bodyIndent += "    ";
                sb.AppendLine($"{bodyIndent}this.{Id(p.Name)} = __p_{p.Name};");
            }

            // Build the combined parameter label: "N=10, Mode=A"
            var labelParts = model.ParamsProperties.Select(p => $"{p.Name}={{__p_{p.Name}}}");
            sb.AppendLine($"{bodyIndent}var __paramLabel = $\"{string.Join(", ", labelParts)}\";");
            sb.AppendLine();
        }

        // ── GlobalSetup ──────────────────────────────────────────────
        if (model.GlobalSetupMethod is not null)
        {
            var awaitPrefix = model.GlobalSetupMethod.IsAsync ? "await " : "";
            sb.AppendLine($"{bodyIndent}{awaitPrefix}this.{Id(model.GlobalSetupMethod.Name)}();");
            sb.AppendLine();
        }

        // ── Benchmarks + comparisons ─────────────────────────────────
        // Wrapped in try/finally so [GlobalCleanup] runs even when a
        // benchmark throws.
        var contentIndent = bodyIndent + "    ";
        if (model.GlobalCleanupMethod is not null)
        {
            sb.AppendLine($"{bodyIndent}try");
            sb.AppendLine($"{bodyIndent}{{");
        }

        foreach (var method in model.Methods)
        {
            var nameExpr = hasParams
                ? $"$\"{method.Name} [{{__paramLabel}}]\""
                : $"\"{method.Name}\"";

            // A synchronous method only needs the async runner path when the
            // surrounding class awaits something for it: the method itself, or
            // its per-sample setup/teardown. Otherwise emit the direct sync
            // path even in a class that has other async members — the async
            // wrapper adds measurable per-iteration overhead.
            var needsAsyncPath =
                isAsync
                && (
                    method.IsAsync
                    || (model.IterationSetupMethod?.IsAsync ?? false)
                    || (model.IterationCleanupMethod?.IsAsync ?? false)
                );

            if (needsAsyncPath)
            {
                EmitAsyncBenchmark(
                    sb,
                    model,
                    method,
                    contentIndent,
                    nameExpr,
                    hasIterSetup,
                    hasIterCleanup
                );
            }
            else if (hasIterSetup || hasIterCleanup)
            {
                EmitSyncBenchmarkWithIter(
                    sb,
                    model,
                    method,
                    contentIndent,
                    nameExpr,
                    hasIterSetup,
                    hasIterCleanup
                );
            }
            else
            {
                sb.AppendLine(
                    $"{contentIndent}var __r_{method.Name} = {Bench}.Benchmark.Run({nameExpr}, () => this.{Id(method.Name)}(), config);"
                );
            }

            sb.AppendLine($"{contentIndent}__results.Add(__r_{method.Name});");
            sb.AppendLine();
        }

        // ── Comparisons (if a baseline exists) ──────────────────────
        var baselineMethod = model.Methods.FirstOrDefault(m => m.IsBaseline);
        if (baselineMethod is not null)
        {
            foreach (var method in model.Methods)
            {
                if (method.IsBaseline)
                    continue;

                var compNameExpr = hasParams
                    ? $"$\"{method.Name} vs {baselineMethod.Name} [{{__paramLabel}}]\""
                    : $"\"{method.Name} vs {baselineMethod.Name}\"";
                var categoryExpr = hasParams ? "__paramLabel" : "null";

                sb.AppendLine(
                    $"{contentIndent}__comparisons.Add(new {Bench}.ComparisonResult({compNameExpr}, __r_{baselineMethod.Name}, __r_{method.Name}, {categoryExpr}));"
                );
            }
            sb.AppendLine();
        }

        // ── GlobalCleanup ────────────────────────────────────────────
        if (model.GlobalCleanupMethod is not null)
        {
            sb.AppendLine($"{bodyIndent}}}");
            sb.AppendLine($"{bodyIndent}finally");
            sb.AppendLine($"{bodyIndent}{{");
            var awaitPrefix = model.GlobalCleanupMethod.IsAsync ? "await " : "";
            sb.AppendLine(
                $"{contentIndent}{awaitPrefix}this.{Id(model.GlobalCleanupMethod.Name)}();"
            );
            sb.AppendLine($"{bodyIndent}}}");
            sb.AppendLine();
        }

        // ── Close [Params] loops ─────────────────────────────────────
        if (hasParams)
        {
            for (var i = model.ParamsProperties.Length - 1; i >= 0; i--)
            {
                bodyIndent = bodyIndent.Substring(0, bodyIndent.Length - 4);
                sb.AppendLine($"{bodyIndent}}}");
            }
            sb.AppendLine();
        }

        // ── Return BenchmarkSuite ────────────────────────────────────
        var descExpr = model.Description is not null
            ? EscapeStringLiteral(model.Description)
            : "null";

        sb.AppendLine($"{m2}__sw.Stop();");
        sb.AppendLine($"{m2}var __suite = new {Bench}.BenchmarkSuite(");
        sb.AppendLine($"{m2}    {CSharpLiterals.StringLiteral(model.ClassName)},");
        sb.AppendLine($"{m2}    new {Bench}.EnvironmentInfo");
        sb.AppendLine($"{m2}    {{");
        sb.AppendLine($"{m2}#if NET8_0_OR_GREATER");
        sb.AppendLine(
            $"{m2}        ExecutionMode = global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported"
        );
        sb.AppendLine($"{m2}            ? {Bench}.RuntimeExecutionMode.Jit");
        sb.AppendLine($"{m2}            : {Bench}.RuntimeExecutionMode.NativeAot,");
        sb.AppendLine($"{m2}#endif");
        sb.AppendLine($"{m2}    }},");
        sb.AppendLine($"{m2}    __results,");
        sb.AppendLine($"{m2}    __sw.Elapsed,");
        sb.AppendLine($"{m2}    description: {descExpr},");
        sb.AppendLine($"{m2}    comparisons: __comparisons);");

        if (isAsync)
        {
            sb.AppendLine($"{m2}return __suite;");
        }
        else
        {
            // Batch 0 · 0.7 (B3-C5). A pure-sync class must return the suite through
            // the ValueTask<T> constructor, not ValueTask.FromResult: the non-generic
            // ValueTask.FromResult only exists in .NET 5+; netstandard2.0 / net472
            // consumers get it from System.Threading.Tasks.Extensions 4.6.3, whose
            // ns2.0 asset has no such method → CS0117. The constructor exists on
            // every TFM, and for a completed task it is exactly as allocation-free
            // as FromResult (IValueTaskSource-free, same struct state).
            // The async path above is unchanged (`return __suite;` already uses the
            // same constructor through the implicit conversion).
            sb.AppendLine($"{m2}return new {ValueTaskType}<{Bench}.BenchmarkSuite>(__suite);");
        }

        // ── Close method / class / namespace ─────────────────────────
        sb.AppendLine($"{m1}}}");
        sb.AppendLine($"{indent}}}");

        if (model.Namespace is not null)
            sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Batch 1 · 1.2 (B3-C3): every identifier this emitter writes goes through
    /// here. <c>ISymbol.Name</c> drops the <c>@</c> that made a keyword name
    /// legal (<c>@lock</c> arrives as <c>lock</c>), so pasting it straight into
    /// the generated source produced <c>this.lock()</c> — CS1003, pointing at a
    /// file the user never wrote.
    /// </summary>
    private static string Id(string name) => IdentifierEscaping.EscapeIdentifier(name);

    private static void EmitSyncBenchmarkWithIter(
        StringBuilder sb,
        BenchmarkClassModel model,
        BenchmarkMethodModel method,
        string bodyIndent,
        string nameExpr,
        bool hasIterSetup,
        bool hasIterCleanup
    )
    {
        sb.AppendLine(
            $"{bodyIndent}{SystemAction} __action_{method.Name} = () => this.{Id(method.Name)}();"
        );

        var setupArg = hasIterSetup
            ? $"({SystemAction})(() => this.{Id(model.IterationSetupMethod!.Name)}())"
            : "null";
        var teardownArg = hasIterCleanup
            ? $"({SystemAction})(() => this.{Id(model.IterationCleanupMethod!.Name)}())"
            : "null";

        sb.AppendLine($"{bodyIndent}var __r_{method.Name} = {Bench}.Benchmark.Run(");
        sb.AppendLine($"{bodyIndent}    {nameExpr},");
        sb.AppendLine($"{bodyIndent}    __action_{method.Name},");
        sb.AppendLine($"{bodyIndent}    warmup: __action_{method.Name},");
        sb.AppendLine($"{bodyIndent}    config: config,");
        sb.AppendLine($"{bodyIndent}    setup: {setupArg},");
        sb.AppendLine($"{bodyIndent}    teardown: {teardownArg});");
    }

    private static void EmitAsyncBenchmark(
        StringBuilder sb,
        BenchmarkClassModel model,
        BenchmarkMethodModel method,
        string bodyIndent,
        string nameExpr,
        bool hasIterSetup,
        bool hasIterCleanup
    )
    {
        // Always wrap in Func<Task> for async class
        var wrap = method.IsAsync
            ? $"async () => {{ await this.{Id(method.Name)}(); }}"
            : $"async () => {{ this.{Id(method.Name)}(); }}";

        var setupArg = GetAsyncIterArg(model.IterationSetupMethod);
        var teardownArg = GetAsyncIterArg(model.IterationCleanupMethod);

        if (hasIterSetup || hasIterCleanup)
        {
            sb.AppendLine($"{bodyIndent}var __r_{method.Name} = await {Bench}.Benchmark.RunAsync(");
            sb.AppendLine($"{bodyIndent}    {nameExpr},");
            sb.AppendLine($"{bodyIndent}    {wrap},");
            sb.AppendLine($"{bodyIndent}    warmup: {wrap},");
            sb.AppendLine($"{bodyIndent}    config: config,");
            sb.AppendLine($"{bodyIndent}    setup: {setupArg},");
            sb.AppendLine($"{bodyIndent}    teardown: {teardownArg});");
        }
        else
        {
            sb.AppendLine(
                $"{bodyIndent}var __r_{method.Name} = await {Bench}.Benchmark.RunAsync({nameExpr}, {wrap}, config);"
            );
        }
    }

    private static string GetAsyncIterArg(LifecycleMethodInfo? method)
    {
        if (method is null)
            return "null";

        return method.IsAsync
            ? $"async () => {{ await this.{Id(method.Name)}(); }}"
            : $"async () => {{ this.{Id(method.Name)}(); }}";
    }

    // Batch 1 · 1.3 (B3-C4): the description used to go through Emitter.EscapeRaw —
    // a second copy of the escape table that, like the [Params] one in
    // CSharpLiteralFormatter, stopped at 0x20 and let U+0085/U+2028/U+2029
    // truncate the literal. Both call sites now share CSharpLiterals.
    private static string EscapeStringLiteral(string s) => CSharpLiterals.StringLiteral(s);
}
