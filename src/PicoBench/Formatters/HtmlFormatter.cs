    #region Results Table

    private void AppendResultsTable(StringBuilder sb, List<BenchmarkResult> results)
    {
        // Batch 2 · 2.4 (B2-M5/M6): same table unit as Console and Markdown, chosen
        // by the same rule and named in the same header slot.
        var unit = TableUnit(PerOpValues(results));

        sb.AppendLine("<table>");
        sb.AppendLine("<thead><tr>");
        sb.AppendLine("<th>Name</th>");
        sb.AppendLine($"<th class=\"number\">Avg ({unit.Symbol})</th>");
        sb.AppendLine($"<th class=\"number\">P50 ({unit.Symbol})</th>");

        if (Options.IncludePercentiles)
        {
            sb.AppendLine($"<th class=\"number\">P90 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">P95 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">P99 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">StdErr ({unit.Symbol})</th>");
            sb.AppendLine("<th class=\"number\">RSD (%)</th>");
        }

        if (Options.IncludeCpuCycles)
        {
            sb.AppendLine($"<th class=\"number\">{CpuCyclesHeader}</th>");
        }

        if (Options.IncludeGcInfo)
        {
            sb.AppendLine("<th>GC (0/1/2)</th>");
        }

        sb.AppendLine("</tr></thead>");
        sb.AppendLine("<tbody>");

        foreach (var result in results)
        {
            var s = result.Statistics;
            sb.AppendLine("<tr>");
            sb.AppendLine(
                $"<td>{Escape(result.Name)}{MeasurementLimitMarker(s)}</td>"
            );
            sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.Avg, unit)}</td>");
            sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.P50, unit)}</td>");

            if (Options.IncludePercentiles)
            {
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.P90, unit)}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.P95, unit)}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.P99, unit)}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(s, s.StandardError, unit)}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatMetric(s.RelativeStdDevPercent, 1)}</td>");
            }

            if (Options.IncludeCpuCycles)
            {
                sb.AppendLine($"<td class=\"number\">{FormatCycles(s)}</td>");
            }

            if (Options.IncludeGcInfo)
            {
                sb.AppendLine($"<td class=\"gc-info\">{FormatGcInfo(s.GcInfo)}</td>");
            }

            sb.AppendLine("</tr>");
        }

        sb.AppendLine("</tbody>");
        sb.AppendLine("</table>");

        AppendMeasurementLimitNote(sb, results.Select(static r => r.Statistics));

        var noisy = results.Where(static r => r.Statistics.HasHighVariance).ToList();
        if (noisy.Count > 0)
        {
            sb.AppendLine(
                $"<p class=\"note\">noise: high variance (RSD &gt;= 10%): {string.Join(", ", noisy.Select(static r => $"{Escape(r.Name)} ({FormatMetric(r.Statistics.RelativeStdDevPercent, 1)}% RSD)"))}; treat the difference as unresolved.</p>"
            );
        }
    }

    /// <summary>
    /// Renders a per-operation cell in the table's unit. A value the run could not
    /// resolve above the harness floor is written as an upper bound
    /// (<c>&lt;limit</c>), and a run whose clock never advanced is written as "not
    /// measured".
    /// </summary>
    private string FormatPerOp(Statistics statistics, double nanoseconds, TimeUnit unit) =>
        statistics.Unmeasured
            ? NotCollected
            : statistics.ResolutionLimited
                ? "&lt;" + BoundCellValue(unit, statistics.ResolutionLimitNanoseconds)
                : MetricCell(unit, nanoseconds);

    /// <summary>
    /// Every per-operation figure the results table holds; the table's unit is
    /// chosen from the largest of them (Batch 2 · 2.4).
    /// </summary>
    private static IEnumerable<double> PerOpValues(List<BenchmarkResult> results)
    {
        foreach (var result in results)
        {
            var s = result.Statistics;
            yield return s.Avg;
            yield return s.P50;
            yield return s.P90;
            yield return s.P95;
            yield return s.P99;
            yield return s.StandardError;
        }
    }

    /// <summary>Every per-operation figure a statistics object contributes.</summary>
    private static IEnumerable<double> PerOpValues(Statistics statistics)
    {
        yield return statistics.Avg;
        yield return statistics.P50;
        yield return statistics.P90;
        yield return statistics.P99;
        yield return statistics.StandardError;
    }

    /// <summary>
    /// Renders the cycle cell. <c>~</c> marks a process-wide counter or a
    /// monotonic-clock proxy rather than a thread-scoped CPU cycle count.
    /// </summary>
    private static string FormatCycles(Statistics statistics) =>
        statistics.CpuCyclesAreApproximate
            ? "~" + FormatMetric(statistics.CpuCyclesPerOp, 0)
            : FormatMetric(statistics.CpuCyclesPerOp, 0);

    /// <summary>
    /// Header of the CPU-cycle column, spelled the same way in the results table
    /// and in the comparison table (T4 · format parity): both tables hold the same
    /// kind of cell, so they must name it the same way.
    /// </summary>
    private const string CpuCyclesHeader = "CPU Cycles";

    /// <summary>
    /// The marker a per-operation cell carries next to its value, as the
    /// <c>note</c> span the results table uses: <c>(unmeasured)</c> when the clock
    /// never advanced, <c>(below resolution)</c> when the value sits at the harness
    /// floor. Shared by both tables, so one <see cref="Statistics"/> is marked the
    /// same way in each.
    /// </summary>
    private static string MeasurementLimitMarker(Statistics statistics) =>
        statistics.Unmeasured
            ? " <span class=\"note\">(unmeasured)</span>"
            : statistics.ResolutionLimited
                ? " <span class=\"note\">(below resolution)</span>"
                : "";

    /// <summary>
    /// The note that explains those markers, printed under a table whose cells use
    /// them (shared by the results table and the comparison table): an upper bound
    /// or a value that was never measured is not a number the document can leave
    /// unexplained. A table whose cells are all plain numbers prints none.
    /// </summary>
    private void AppendMeasurementLimitNote(StringBuilder sb, IEnumerable<Statistics> statistics)
    {
        var list = statistics.ToList();
        if (list.Exists(static s => s.Unmeasured))
            sb.AppendLine(
                "<p class=\"note\">unmeasured: the clock did not advance for the whole sample, so no per-operation value is shown (the timing source's granularity is coarser than the work).</p>"
            );
        else if (list.Exists(static s => s.ResolutionLimited))
            sb.AppendLine(
                "<p class=\"note\">below resolution: the value is at the measurement harness' own floor, so only an upper bound is shown.</p>"
            );

        // R-T4 · B7: a table with no cycle column prints no `~`, so it explains none.
        if (Options.IncludeCpuCycles && list.Exists(static s => s.CpuCyclesAreApproximate))
            sb.AppendLine(ApproximateCycles.HtmlPrefix + ApproximateCycles.Sentence + "</p>");
    }

    // The `~` sentence is shared with the other two display formats
    // (<see cref="ApproximateCycles"/>); this format adds only its own <p> wrapper (R-T4 · B5).

