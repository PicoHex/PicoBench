    #region Comparisons

    private void AppendComparisonSummary(
        StringBuilder sb,
        List<ComparisonResult> comparisons
    )
    {
        var wins = comparisons.Count(c => c.IsFaster);
        var total = comparisons.Count;

        // Batch 2 · 2.2 (B2-M2): non-finite ratios are excluded from the aggregate
        // and disclosed below the box instead of turning it into ∞/NaN.
        var ratios = SpeedupAggregate.From(comparisons);

        sb.AppendLine("<div class=\"summary-box\">");

        sb.AppendLine("<div class=\"summary-item\">");
        sb.AppendLine($"<div class=\"value\">{wins} / {total}</div>");
        sb.AppendLine("<div class=\"label\">Scenarios Won</div>");
        sb.AppendLine("</div>");

        sb.AppendLine("<div class=\"summary-item\">");
        sb.AppendLine(
            $"<div class=\"value\">{FormatSpeedupValue(ratios.Average, Options.SpeedupDecimalPlaces)}</div>"
        );
        sb.AppendLine("<div class=\"label\">Average Speedup</div>");
        sb.AppendLine("</div>");

        sb.AppendLine("<div class=\"summary-item\">");
        sb.AppendLine(
            $"<div class=\"value\">{FormatSpeedupValue(ratios.Maximum, Options.SpeedupDecimalPlaces)}</div>"
        );
        sb.AppendLine("<div class=\"label\">Maximum Speedup</div>");
        sb.AppendLine("</div>");

        sb.AppendLine("</div>");

        if (ratios.Excluded > 0)
            sb.AppendLine($"<p class=\"note\">{Escape(ratios.DescribeExcluded())}</p>");
    }

    private void AppendComparisonsTable(StringBuilder sb, List<ComparisonResult> comparisons)
    {
        // Flatten to rows with Provider column
        var rows =
            new List<(string TestCase, string Provider, Statistics Stats, double? Speedup)>();
        foreach (var c in comparisons)
        {
            rows.Add((c.Name, Options.CandidateLabel, c.Candidate.Statistics, c.Speedup));
            rows.Add((c.Name, Options.BaselineLabel, c.Baseline.Statistics, null));
        }

        // Batch 2 · 2.4 (B2-M5): `P50 | P90 | P99 | StdErr` were bare headers here
        // while Console wrote `Avg (ns)`. One unit for the table, named in every
        // per-operation header, exactly as in the other two display formats.
        var unit = TableUnit(rows.Select(r => r.Stats).SelectMany(PerOpValues));

        sb.AppendLine("<table>");
        sb.AppendLine("<thead><tr>");
        sb.AppendLine("<th>Test Case</th>");
        sb.AppendLine($"<th class=\"number\">Avg ({unit.Symbol})</th>");
        sb.AppendLine("<th class=\"number\">Speedup</th>");

        if (Options.IncludePercentiles)
        {
            sb.AppendLine($"<th class=\"number\">P50 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">P90 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">P99 ({unit.Symbol})</th>");
            sb.AppendLine($"<th class=\"number\">StdErr ({unit.Symbol})</th>");
            sb.AppendLine("<th class=\"number\">RSD (%)</th>");
        }

        if (Options.IncludeCpuCycles)
        {
            sb.AppendLine($"<th class=\"number\">{CpuCyclesHeader}</th>");
        }

        if (Options.IncludeGcInfo)
        {
            sb.AppendLine("<th>GC</th>");
        }

        sb.AppendLine("</tr></thead>");
        sb.AppendLine("<tbody>");

        foreach (var row in rows)
        {
            var testCase = $"{row.Provider} * {row.TestCase}";
            var speedupClass = row.Speedup.HasValue ? GetSpeedupClass(row.Speedup.Value) : "";
            var indicator = row.Speedup.HasValue ? GetSpeedupIndicator(row.Speedup.Value) : "";
            var speedupText = row.Speedup.HasValue
                ? $"<span class=\"speedup {speedupClass}\">{FormatSpeedup(row.Speedup.Value)}</span><span class=\"indicator\">{indicator}</span>"
                : "";

            var stats = row.Stats;
            // T4 · format parity: the per-operation cells of the comparison table
            // carry the same `note` span the results table puts next to a value that
            // is an upper bound or was never measured, so the marker cannot differ
            // between the two tables of the document.
            var limit = MeasurementLimitMarker(stats);
            sb.AppendLine("<tr>");
            sb.AppendLine($"<td>{Escape(testCase)}</td>");
            sb.AppendLine($"<td class=\"number\">{FormatPerOp(stats, stats.Avg, unit)}{limit}</td>");
            sb.AppendLine($"<td class=\"number\">{speedupText}</td>");

            if (Options.IncludePercentiles)
            {
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(stats, stats.P50, unit)}{limit}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(stats, stats.P90, unit)}{limit}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(stats, stats.P99, unit)}{limit}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatPerOp(stats, stats.StandardError, unit)}{limit}</td>");
                sb.AppendLine($"<td class=\"number\">{FormatMetric(stats.RelativeStdDevPercent, 1)}</td>");
            }

            if (Options.IncludeCpuCycles)
            {
                // The same cell as the results row: a proxy counter keeps its `~`.
                sb.AppendLine($"<td class=\"number\">{FormatCycles(row.Stats)}</td>");
            }

            if (Options.IncludeGcInfo)
            {
                sb.AppendLine($"<td class=\"gc-info\">{FormatGcInfo(stats.GcInfo)}</td>");
            }

            sb.AppendLine("</tr>");
        }

        sb.AppendLine("</tbody>");
        sb.AppendLine("</table>");

        AppendMeasurementLimitNote(sb, rows.Select(static r => r.Stats));
    }

    private static string GetSpeedupClass(double speedup)
    {
        return speedup switch
        {
            >= 3 => "very-fast",
            >= 1.5 => "fast",
            >= 1 => "neutral",
            _ => "slow",
        };
    }

