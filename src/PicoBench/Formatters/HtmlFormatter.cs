namespace PicoBench.Formatters;

/// <summary>
/// Formats benchmark results as HTML with embedded CSS styling.
/// No external dependencies required.
/// </summary>
public sealed class HtmlFormatter(FormatterOptions? options = null) : FormatterBase(options)
{
    /// <inheritdoc />
    protected override string FormatCore(IEnumerable<BenchmarkResult> results)
    {
        var sb = new StringBuilder();
        var list = results.ToList();

        AppendHtmlHeader(sb, "Benchmark Results");
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"container\">");
        sb.AppendLine("<h1>Benchmark Results</h1>");

        if (list.Count == 0)
        {
            sb.AppendLine("<p class=\"no-data\">No results available.</p>");
        }
        else
        {
            AppendResultsTable(sb, list);
        }

        sb.AppendLine("</div>");
        AppendHtmlFooter(sb);

        return sb.ToString();
    }

    /// <inheritdoc />
    protected override string FormatCore(IEnumerable<ComparisonResult> comparisons)
    {
        var sb = new StringBuilder();
        var list = comparisons.ToList();

        AppendHtmlHeader(sb, "Benchmark Comparison");
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"container\">");
        sb.AppendLine("<h1>Benchmark Comparison</h1>");

        if (list.Count == 0)
        {
            sb.AppendLine("<p class=\"no-data\">No comparison results available.</p>");
        }
        else
        {
            AppendComparisonSummary(sb, list);
            AppendComparisonsTable(sb, list);
        }

        sb.AppendLine("</div>");
        AppendHtmlFooter(sb);

        return sb.ToString();
    }

    /// <inheritdoc />
    protected override string FormatCore(BenchmarkSuite suite)
    {
        var sb = new StringBuilder();

        AppendHtmlHeader(sb, suite.Name);
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"container\">");

        // Header
        sb.AppendLine($"<h1>{Escape(suite.Name)}</h1>");

        if (!string.IsNullOrEmpty(suite.Description))
        {
            sb.AppendLine($"<p class=\"description\">{Escape(suite.Description!)}</p>");
        }

        // Environment info
        if (Options.IncludeEnvironment)
        {
            sb.AppendLine("<div class=\"environment\">");
            sb.AppendLine($"<strong>Environment:</strong> {Escape(suite.Environment.ToString())}");
            sb.AppendLine("<br>");
            sb.AppendLine(
                $"<strong>CPU Counter:</strong> {Escape(EnvironmentInfo.DescribeCpuCycleMeasurement(suite.Environment.CpuCycleMeasurement))}"
            );

            if (!suite.Environment.CpuCyclesAvailable)
                sb.AppendLine(
                    "<br><strong>CPU Counter Note:</strong> unavailable on this platform/runtime"
                );
            else if (!suite.Environment.CpuCyclesAreMeaningful)
                sb.AppendLine(
                    "<br><strong>CPU Counter Note:</strong> proxy timing source, not true CPU cycles"
                );

            sb.AppendLine("</div>");
        }

        if (Options.IncludeTimestamp)
        {
            sb.AppendLine("<div class=\"metadata\">");
            sb.AppendLine(
                $"<span><strong>Timestamp:</strong> {FormatTimestamp(suite.Timestamp)} UTC</span>"
            );
            sb.AppendLine(
                $"<span><strong>Duration:</strong> {FormatDuration(suite.Duration)}</span>"
            );
            sb.AppendLine("</div>");
        }

        // Comparisons summary and table
        if (suite.Comparisons?.Count > 0)
        {
            sb.AppendLine("<h2>Comparison Summary</h2>");
            AppendComparisonSummary(sb, suite.Comparisons.ToList());

            sb.AppendLine("<h2>Detailed Comparisons</h2>");
            AppendComparisonsTable(sb, suite.Comparisons.ToList());
        }

        // Results table
        if (suite.Results.Count > 0)
        {
            sb.AppendLine("<h2>All Results</h2>");
            AppendResultsTable(sb, suite.Results.ToList());
        }

        sb.AppendLine("</div>");
        AppendHtmlFooter(sb);

        return sb.ToString();
    }

    #region HTML Structure

    private static void AppendHtmlHeader(StringBuilder sb, string title)
    {
        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head>");
        sb.AppendLine("<meta charset=\"UTF-8\">");
        sb.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">");
        sb.AppendLine($"<title>{Escape(title)}</title>");
        AppendStyles(sb);
        sb.AppendLine("</head>");
    }

    private static void AppendHtmlFooter(StringBuilder sb)
    {
        sb.AppendLine("<footer>");
        sb.AppendLine(
            $"<p>Generated by PicoBench at {FormatTimestamp(DateTime.UtcNow)} UTC</p>"
        );
        sb.AppendLine("</footer>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");
    }

