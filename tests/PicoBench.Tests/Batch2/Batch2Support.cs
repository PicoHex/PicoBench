namespace PicoBench.Tests.Batch2;

using System.Text;
using System.Text.RegularExpressions;
using PicoBench.Tests.Batch0;

/// <summary>
/// Shared helpers for the Batch 2 "output fidelity" tests
/// (<c>.review-2026-11/00-FINAL-VERDICT.md</c> §5, items 2.1 / 2.2 / 2.3).
/// <para>
/// The fixtures are built by hand instead of by measurement so every number,
/// timestamp and duration in the output is known up front: a byte-for-byte
/// culture comparison is only meaningful when the only thing that can differ
/// between two renderings is the culture itself.
/// </para>
/// </summary>
internal static class Batch2Support
{
    /// <summary>The one timestamp every fixture uses (a fixed UTC instant).</summary>
    internal static readonly DateTime FixedTimestamp = new(2026, 11, 2, 13, 45, 0, DateTimeKind.Utc);

    /// <summary>The one suite duration every fixture uses.</summary>
    internal static readonly TimeSpan FixedDuration = TimeSpan.FromSeconds(2.5);

    /// <summary>Gregorian rendering of <see cref="FixedTimestamp"/>, culture-free.</summary>
    internal const string FixedTimestampText = "2026-11-02 13:45:00";

    /// <summary>Calendars that must never leak into the output (th-TH / ar-SA years).</summary>
    internal static readonly string[] ForeignYearPrefixes = ["2569", "1448"];

    /// <summary>Culture names Batch 2 · 2.1 requires to be byte-identical.</summary>
    internal static readonly string[] RequiredCultures = ["de-DE", "th-TH", "ar-SA"];

    private const string VolatileClockPattern =
        @"Generated by PicoBench at \d{1,4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC";

    private static Statistics Stats(
        double avg,
        double relativeStdDevPercent = 1.0,
        bool resolutionLimited = false,
        double resolutionLimitNanoseconds = 0.0,
        double overheadNs = 0.0,
        int unmeasuredSampleCount = 0,
        double cpuCyclesPerOp = 300.0
    ) =>
        new()
        {
            Avg = avg,
            P50 = avg * 0.95,
            P90 = avg * 1.10,
            P95 = avg * 1.15,
            P99 = avg * 1.25,
            Min = avg * 0.80,
            Max = avg * 1.30,
            StdDev = avg * 0.10,
            StandardError = avg * 0.10 / Math.Sqrt(5),
            RelativeStdDevPercent = relativeStdDevPercent,
            CpuCyclesPerOp = cpuCyclesPerOp,
            GcInfo = GcInfoFactory.Create(),
            ResolutionLimited = resolutionLimited,
            ResolutionLimitNanoseconds = resolutionLimitNanoseconds,
            OverheadNs = overheadNs,
            UnmeasuredSampleCount = unmeasuredSampleCount,
        };

    /// <summary>
    /// A suite that touches every numeric rendering site the four formatters
    /// have: a plain row, a high-variance row, a below-resolution row and an
    /// unmeasured row, plus one comparison.
    /// </summary>
    internal static BenchmarkSuite RichSuite(string? description = "A rich suite")
    {
        var results = new List<BenchmarkResult>
        {
            Result("Plain_Op", Stats(150.5), iterationsPerSample: 1000, sampleCount: 100),
            Result("Noisy_Op", Stats(250.0, relativeStdDevPercent: 12.3)),
            Result(
                "Below_Resolution_Op",
                Stats(
                    0.2,
                    resolutionLimited: true,
                    resolutionLimitNanoseconds: 0.345,
                    overheadNs: 0.1875,
                    cpuCyclesPerOp: 1.0
                )
            ),
            Result("Unmeasured_Op", Stats(0.2, unmeasuredSampleCount: 2, cpuCyclesPerOp: 0.0)),
        };

        var comparisons = new List<ComparisonResult>
        {
            Comparison(
                "Faster_Case",
                Stats(100.0, relativeStdDevPercent: 1.0),
                Stats(50.0, relativeStdDevPercent: 2.0),
                baselineIterations: 1000,
                candidateIterations: 2500,
                baselineSamples: 20,
                candidateSamples: 40
            ),
        };

        return new BenchmarkSuite(
            name: "RichSuite",
            environment: new EnvironmentInfo(),
            results: results,
            duration: FixedDuration,
            description: description,
            comparisons: comparisons,
            timestamp: FixedTimestamp
        );
    }

    /// <summary>A suite whose only payload is the given comparisons.</summary>
    internal static BenchmarkSuite SuiteWithComparisons(
        IReadOnlyList<ComparisonResult> comparisons,
        string description = "comparison suite"
    ) =>
        new(
            name: "ComparisonSuite",
            environment: new EnvironmentInfo(),
            results: [],
            duration: FixedDuration,
            description: description,
            comparisons: comparisons,
            timestamp: FixedTimestamp
        );

    internal static BenchmarkResult Result(
        string name,
        Statistics statistics,
        int iterationsPerSample = 1000,
        int sampleCount = 100,
        string? category = "CategoryA"
    ) =>
        new(
            name: name,
            statistics: statistics,
            iterationsPerSample: iterationsPerSample,
            sampleCount: sampleCount,
            category: category,
            timestamp: FixedTimestamp
        );

    internal static ComparisonResult Comparison(
        string name,
        Statistics baseline,
        Statistics candidate,
        int baselineIterations = 1000,
        int candidateIterations = 1000,
        int baselineSamples = 20,
        int candidateSamples = 20
    ) =>
        new(
            name,
            Result("Baseline_" + name, baseline, baselineIterations, baselineSamples),
            Result("Candidate_" + name, candidate, candidateIterations, candidateSamples)
        );

    /// <summary>
    /// Renders one suite through every output format (the four formatters plus
    /// the summary box and the single-result console view), keyed by format.
    /// </summary>
    internal static Dictionary<string, string> RenderAll(BenchmarkSuite suite)
    {
        var map = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["console"] = new ConsoleFormatter().Format(suite),
            ["csv"] = new CsvFormatter().Format(suite),
            ["markdown"] = new MarkdownFormatter().Format(suite),
            ["html"] = new HtmlFormatter().Format(suite),
            ["summary"] = SummaryFormatter.Format(suite.Comparisons!, suite.Duration),
            ["console-single"] = string.Join(
                "\n",
                suite.Results.Select(static r => new ConsoleFormatter().Format(r))
            ),
            ["markdown-results"] = new MarkdownFormatter().Format(suite.Results),
            ["csv-comparisons"] = new CsvFormatter().Format(suite.Comparisons!),
        };

        foreach (var key in map.Keys.ToList())
            map[key] = MaskVolatileClock(map[key]);

        return map;
    }

    /// <summary>
    /// Blanks the one line of the HTML footer that carries <c>DateTime.UtcNow</c>
    /// (a live clock, not a culture artifact). Without this mask a byte
    /// comparison across three renderings could fail merely because the wall
    /// clock ticked over a second between them.
    /// </summary>
    internal static string MaskVolatileClock(string text) =>
        Regex.Replace(text, VolatileClockPattern, "Generated by PicoBench at <clock> UTC");

    /// <summary>The footer lines that carry the live clock, unmasked.</summary>
    internal static IReadOnlyList<string> VolatileClockLines(string text) =>
        Regex.Matches(text, VolatileClockPattern).Select(static m => m.Value).ToList();

    /// <summary>
    /// Strips the <c>#</c> comment lines the way <c>pandas.read_csv(comment='#')</c>
    /// does: a line whose first character is <c>#</c> is dropped whole — unless the
    /// scan is inside a quoted field, where a <c>#</c> is data.
    /// </summary>
    internal static string StripCommentLines(string csv)
    {
        var sb = new StringBuilder(csv.Length);
        var inQuotes = false;
        var atLineStart = true;
        var i = 0;

        while (i < csv.Length)
        {
            if (atLineStart && !inQuotes && csv[i] == '#')
            {
                // Drop the whole physical line, including its terminator.
                while (i < csv.Length && csv[i] != '\n')
                    i++;
                if (i < csv.Length)
                    i++;
                atLineStart = true;
                continue;
            }

            var c = csv[i];
            if (c == '"')
            {
                if (inQuotes && i + 1 < csv.Length && csv[i + 1] == '"')
                {
                    sb.Append('"').Append('"');
                    i += 2;
                    continue;
                }

                inQuotes = !inQuotes;
            }

            atLineStart = c == '\n';
            sb.Append(c);
            i++;
        }

        return sb.ToString();
    }

    /// <summary>
    /// A minimal RFC 4180 reader: comma separated, <c>"</c> quoted fields with
    /// <c>""</c> escapes and embedded line breaks, one record per line otherwise.
    /// This is the "equivalent parser" Batch 2 · 2.3 allows — the point of the
    /// test is that the file survives a real CSV reader.
    /// </summary>
    internal static List<List<string>> ParseCsv(string text)
    {
        var records = new List<List<string>>();
        var record = new List<string>();
        var field = new StringBuilder();
        var inQuotes = false;
        var fieldStarted = false;
        var i = 0;

        while (i < text.Length)
        {
            var c = text[i];

            if (inQuotes)
            {
                if (c == '"')
                {
                    if (i + 1 < text.Length && text[i + 1] == '"')
                    {
                        field.Append('"');
                        i += 2;
                        continue;
                    }

                    inQuotes = false;
                    i++;
                    continue;
                }

                field.Append(c);
                i++;
                continue;
            }

            switch (c)
            {
                case '"' when !fieldStarted && field.Length == 0:
                    inQuotes = true;
                    fieldStarted = true;
                    i++;
                    continue;

                case ',':
                    record.Add(field.ToString());
                    field.Clear();
                    fieldStarted = false;
                    i++;
                    continue;

                case '\r':
                    i++;
                    continue;

                case '\n':
                    record.Add(field.ToString());
                    field.Clear();
                    fieldStarted = false;
                    if (record.Count > 1 || record[0].Length > 0)
                        records.Add(record);
                    record = new List<string>();
                    i++;
                    continue;

                default:
                    field.Append(c);
                    fieldStarted = true;
                    i++;
                    continue;
            }
        }

        if (field.Length > 0 || record.Count > 0)
        {
            record.Add(field.ToString());
            if (record.Count > 1 || record[0].Length > 0)
                records.Add(record);
        }

        return records;
    }

    /// <summary>
    /// Splits a suite CSV into its two sections the way the README tells a
    /// consumer to: at the section's own <c># Schema: v2; section=…</c> line.
    /// </summary>
    internal static (string Results, string Comparisons) SplitSections(string csv)
    {
        const string marker = "# Schema: v2; section=comparisons";
        var index = csv.IndexOf(marker, StringComparison.Ordinal);
        return index < 0 ? (csv, string.Empty) : (csv[..index], csv[index..]);
    }

    internal static string[] Lines(string text) =>
        text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');

    internal static string Describe<T>(IEnumerable<T> values) =>
        "[" + string.Join(", ", values) + "]";

    internal static void Log(string message) => Batch0Support.Log(message);
}
