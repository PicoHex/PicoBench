namespace PicoBench.Tests.Batch2;

/// <summary>
/// Batch 2 · 2.1 (B2-H1) — regional settings must not be able to change a single
/// byte of the output. The library's "invariant culture" policy used to live in
/// two helper methods only (<c>FormatTime</c> / <c>FormatSpeedup</c>), while the
/// RSD, CPU-cycle, duration, speedup and timestamp figures that the four
/// formatters <em>also</em> print went through <c>$"{x:F1}"</c> interpolation and
/// <c>{dt:yyyy-MM-dd HH:mm:ss}</c>, i.e. through <see cref="CultureInfo.CurrentCulture"/>.
/// </summary>
/// <remarks>
/// The oracle is a whole-document byte comparison: the same suite object is
/// rendered under the invariant culture and under de-DE, th-TH and ar-SA, and
/// every format must come out identical. Positive controls check that the
/// fixture really exercises the offending sites (a metric with a decimal
/// fraction and a Gregorian timestamp), so the comparison cannot pass because
/// the fixture was empty.
/// </remarks>
public class RegionalFormatTests
{
    [Test]
    [Property("Category", "Batch2")]
    [Property("Batch2", "2.1/invariant culture")]
    public async Task EveryFormat_IsByteIdentical_AcrossCultures()
    {
        var baseline = RenderUnder(CultureInfo.InvariantCulture);

        Batch2Support.Log("console head: " + Batch2Support.Lines(baseline["console"])[2]);

        foreach (var cultureName in Batch2Support.RequiredCultures)
        {
            var culture = new CultureInfo(cultureName);
            var actual = RenderUnder(culture);

            foreach (var format in baseline.Keys)
            {
                if (baseline[format] == actual[format])
                    continue;

                var where = FirstDifference(baseline[format], actual[format]);
                await Assert
                    .That(actual[format])
                    .IsEqualTo(baseline[format])
                    .Because($"{format} output differs under {cultureName} near: {where}");
            }
        }
    }

    [Test]
    [Property("Category", "Batch2")]
    [Property("Batch2", "2.1/invariant culture")]
    public async Task Timestamp_StaysGregorianUtc_InEveryCulture()
    {
        foreach (var cultureName in Batch2Support.RequiredCultures)
        {
            var rendered = RenderUnder(new CultureInfo(cultureName));

            // Every document that prints the suite timestamp prints the same
            // Gregorian instant, and none of them prints a Buddhist (2569) or
            // Umm al-Qura (1448) year next to the word "UTC".
            foreach (var format in new[] { "console", "csv", "markdown", "html", "summary" })
            {
                if (format == "summary")
                    continue; // the summary box carries no timestamp

                await Assert
                    .That(rendered[format])
                    .Contains(Batch2Support.FixedTimestampText)
                    .Because($"{format} under {cultureName} lost the Gregorian timestamp");
            }

            foreach (var format in rendered.Keys)
            {
                foreach (var foreign in Batch2Support.ForeignYearPrefixes)
                {
                    await Assert
                        .That(rendered[format].Contains(foreign, StringComparison.Ordinal))
                        .IsFalse()
                        .Because($"{format} under {cultureName} printed the non-Gregorian year {foreign}");
                }
            }
        }
    }

    /// <summary>
    /// The HTML footer is stamped with <c>DateTime.UtcNow</c> at render time, so
    /// the whole-document comparison masks it. This test still pins it: the
    /// footer must carry a Gregorian year under every culture as well, otherwise
    /// the mask would hide exactly the bug 2.1 is about.
    /// </summary>
    [Test]
    [Property("Category", "Batch2")]
    [Property("Batch2", "2.1/invariant culture")]
    public async Task HtmlFooterClock_StaysGregorian_InEveryCulture()
    {
        foreach (var cultureName in Batch2Support.RequiredCultures)
        {
            var html = RenderUnder(new CultureInfo(cultureName), maskClock: false)["html"];
            var footer = Batch2Support.VolatileClockLines(html);

            await Assert
                .That(footer.Count)
                .IsEqualTo(1)
                .Because($"html under {cultureName} has no '<footer>' clock line");

            Batch2Support.Log($"[{cultureName}] footer: {footer[0]}");

            await Assert
                .That(footer[0].StartsWith("Generated by PicoBench at 20", StringComparison.Ordinal))
                .IsTrue()
                .Because($"html under {cultureName} printed a non-Gregorian footer year: {footer[0]}");
        }
    }

    /// <summary>
    /// Positive control: the fixture must contain a value whose rendering is
    /// culture-sensitive <em>if</em> the interpolation sites are left alone
    /// (12.3 RSD, 2.50s duration) and a timestamp whose calendar is not.
    /// </summary>
    [Test]
    [Property("Category", "Batch2")]
    [Property("Batch2", "2.1/invariant culture")]
    public async Task Fixture_ExercisesTheCultureSensitiveSites()
    {
        var rendered = RenderUnder(CultureInfo.InvariantCulture);

        await Assert.That(rendered["csv"]).Contains("12.3"); // RSD
        await Assert.That(rendered["csv"]).Contains("2.50s"); // duration
        await Assert.That(rendered["csv"]).Contains(Batch2Support.FixedTimestampText); // timestamp
        await Assert.That(rendered["console-single"]).Contains("0.345"); // F3 overhead site
        await Assert.That(rendered["summary"]).Contains("2.00x"); // speedup
    }

    private static Dictionary<string, string> RenderUnder(CultureInfo culture, bool maskClock = true)
    {
        var original = CultureInfo.CurrentCulture;
        try
        {
            CultureInfo.CurrentCulture = culture;
            var map = Batch2Support.RenderAll(Batch2Support.RichSuite());
            if (maskClock)
                return map;

            // Re-render without the clock mask so the footer can be inspected.
            map["html"] = new HtmlFormatter().Format(Batch2Support.RichSuite());
            return map;
        }
        finally
        {
            CultureInfo.CurrentCulture = original;
        }
    }

    private static string FirstDifference(string expected, string actual)
    {
        var limit = Math.Min(expected.Length, actual.Length);
        for (var i = 0; i < limit; i++)
        {
            if (expected[i] != actual[i])
            {
                var start = Math.Max(0, i - 30);
                return $"@{i}: expected …{expected[start..Math.Min(expected.Length, i + 30)]}…"
                    + $" got …{actual[start..Math.Min(actual.Length, i + 30)]}…";
            }
        }

        return $"lengths differ ({expected.Length} vs {actual.Length}) at end: "
            + (expected.Length > actual.Length ? expected[limit..] : actual[limit..]);
    }
}
