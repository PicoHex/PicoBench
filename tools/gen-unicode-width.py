#!/usr/bin/env python3
"""Regenerate PicoBench's display-width tables from the Unicode Character Database.

Review 40 (F2) found that ``DisplayWidth.IsWide`` covered only two emoji
segments and that ``IsZeroWidth`` recognised only two combining blocks, so a
common emoji (U+1F680) was padded as one cell and a variation selector was
counted as one cell of its own. Both tables are now generated in full from the
UCD and checked in, because the library targets ``netstandard2.0`` and must not
depend on the runtime's Unicode version.

Outputs (both are written, never hand-edited):

  src/PicoBench/Formatters/UnicodeWidthTable.cs
      Two flat ``int[]`` range tables (start, end, start, end, ...):
      zero-width = category Mn/Me/Cf plus the Hangul Jamo medial/final blocks,
      wide       = East_Asian_Width W or F.

  tests/PicoBench.Tests/Batch2/UnicodeWidthSnapshot.txt
      The same ranges as text (``<width> <startHex> <endHex>``), used as the
      test oracle. The test reads this file instead of copying the C# table, so
      a hand-edit that drifts from the UCD has something to disagree with.

Run from the repository root:  python tools/gen-unicode-width.py
"""

from __future__ import annotations

import sys
import unicodedata as u

#: U+00AD SOFT HYPHEN is Cf but has a cell on many terminals; Python's own
#: ``wcwidth`` treats it as zero-width. Keep that convention, spelled out here
#: because it is the one place the category rule is overridden.
SOFT_HYPHEN = 0x00AD

#: Hangul Jamo medial vowels and final consonants combine into the preceding
#: syllable and occupy no cell of their own.
HANGUL_VOWEL_FINAL = ((0x1160, 0x11FF), (0xD7B0, 0xD7FF))

ROOT = "src/PicoBench/Formatters/UnicodeWidthTable.cs"
SNAPSHOT = "tests/PicoBench.Tests/Batch2/UnicodeWidthSnapshot.txt"


def width(code: int) -> int:
    """Display width of one code point: 0, 1 or 2."""
    if code == SOFT_HYPHEN:
        return 1
    for low, high in HANGUL_VOWEL_FINAL:
        if low <= code <= high:
            return 0
    category = u.category(chr(code))
    if category in ("Mn", "Me", "Cf"):
        return 0
    if u.east_asian_width(chr(code)) in ("W", "F"):
        return 2
    return 1


def ranges(target: int) -> list[tuple[int, int]]:
    """Maximal ranges of code points whose width is ``target``."""
    out: list[tuple[int, int]] = []
    start = previous = None
    for code in range(0x110000):
        if width(code) == target:
            if start is None:
                start = code
            previous = code
        elif start is not None:
            out.append((start, previous))
            start = None
    if start is not None:
        out.append((start, previous))
    return out


def cs_table(name: str, ranges_: list[tuple[int, int]]) -> str:
    lines = [
        f"    private static readonly int[] {name} =",
        "    [",
    ]
    for start, end in ranges_:
        lines.append(f"        0x{start:04X}, 0x{end:04X},")
    lines.append("    ];")
    return "\n".join(lines)


def main() -> int:
    zero = ranges(0)
    wide = ranges(2)

    header = f'''// <auto-generated />
// Unicode display width, generated from the Unicode Character Database by
// tools/gen-unicode-width.py. Do not edit by hand: a hand-edited table is what
// review 40 (F2) caught, and the test oracle reads the sibling snapshot file
// rather than believing this source.
//
// Unicode version : {u.unidata_version}
// zero-width ranges: {len(zero)}
// wide ranges      : {len(wide)}
// Regenerate with : python tools/gen-unicode-width.py
namespace PicoBench.Formatters;

/// <summary>
/// The two half-open range tables <see cref="DisplayWidth"/> pads with. Flat
/// <c>int[]</c> pairs (<c>start, end</c>) searched with a binary search, because
/// the library targets <c>netstandard2.0</c> and cannot use the runtime's Unicode
/// tables: the output has to be the same on every runtime.
/// </summary>
internal static class UnicodeWidthTable
{{
'''

    body = (
        cs_table("ZeroWidth", zero)
        + "\n\n"
        + cs_table("Wide", wide)
        + f'''

    /// <summary>True when <paramref name="ranges"/> holds {len(zero) + len(wide)} flat pairs covering <paramref name="code"/>.</summary>
    internal static bool Contains(int[] ranges, int code)
    {{
        var low = 0;
        var high = (ranges.Length / 2) - 1;
        while (low <= high)
        {{
            var middle = low + ((high - low) / 2);
            var start = ranges[middle * 2];
            var end = ranges[(middle * 2) + 1];
            if (code < start)
                high = middle - 1;
            else if (code > end)
                low = middle + 1;
            else
                return true;
        }}

        return false;
    }}
}}
'''
    )

    with open(ROOT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header + body)

    snapshot_lines = [
        "# Unicode display width ranges, from the UCD in Unicode " + u.unidata_version,
        "# Generated by tools/gen-unicode-width.py. One line per maximal range:",
        "#   <cells> <startHex> <endHex>",
        "# Cells: 0 = occupies no cell, 2 = East Asian Wide/Fullwidth.",
        "# Every code point not listed here occupies exactly one cell.",
    ]
    for cells, table in ((0, zero), (2, wide)):
        for start, end in table:
            snapshot_lines.append(f"{cells} 0x{start:04X} 0x{end:04X}")
    with open(SNAPSHOT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(snapshot_lines) + "\n")

    print(f"unicode {u.unidata_version}: {len(zero)} zero-width ranges, {len(wide)} wide ranges")
    print(f"wrote {ROOT} and {SNAPSHOT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
